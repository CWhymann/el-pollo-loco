/**
 * Represents the current state of all tracked keyboard inputs.
 * Each property is true while its key is held down, false when released.
 */
// #region class Keyboard
export class Keyboard {
    // #region Properties
    LEFT = false;
    RIGHT = false;
    UP = false;
    DOWN = false;
    SPACE = false;
    D = false;
    // #endregion
}
// #endregion class Keyboard
